;=====================================================================
;  GRAVASSIST — οι τράπεζες RAM του 6128 ως δίσκος αιθουσών
;
;  Ο 6128 έχει δεύτερα 64 KB που το παιχνίδι δεν άγγιζε καθόλου. Μπαίνουν
;  στη μνήμη με τις οργανώσεις #C4..#C7, οι οποίες αντικαθιστούν ΜΟΝΟ το
;  #4000..#7FFF με τα μπλοκ 4..7 — δηλαδή ακριβώς εκεί όπου ζει ΟΛΟΣ ο
;  εκτελέσιμος κώδικας του παιχνιδιού (#4000..#6A05).
;
;  ΑΠΟ ΑΥΤΟ ΠΡΟΚΥΠΤΕΙ Ο ΜΟΝΟΣ ΚΑΝΟΝΑΣ ΤΟΥ ΑΡΧΕΙΟΥ: ό,τι εκτελείται με
;  ανοιχτό παράθυρο ζει ΕΔΩ, και το αρχείο assembl-άρεται πάνω από το #8000.
;  Με ανοιχτό παράθυρο δεν καλείται τίποτα — ούτε firmware, ούτε ρουτίνα του
;  παιχνιδιού, ούτε καν άλλη ρουτίνα αυτού του αρχείου. Μόνο LDIR.
;  Οι δύο assert στο τέλος το επιβάλλουν· η θέση του include είναι σωστή
;  σήμερα κατά τύχη των μεγεθών των δεδομένων, όχι από σχεδιασμό.
;
;  ΓΙΑΤΙ ΩΜΟ OUT ΚΑΙ ΟΧΙ ΤΟ KL BANK SWITCH (#BD5B): το firmware τελειώνει τη
;  ρουτίνα του με ανεπιφύλακτο EI — δεν μπορείς να το καλέσεις μέσα σε δικό
;  σου κρίσιμο τμήμα — και διαβάζει τη θύρα από τον B' του εναλλακτικού
;  σετ, που ανήκει στο firmware. Το ωμό OUT δεν χρωστά τίποτα σε κανέναν.
;
;  Πηγή για τον μηχανισμό: SOFT968 §2.5 και §15, και η ίδια η ROM του 6128
;  (`ld bc,$7fc0 / out (c),c`).
;=====================================================================

; Ο gate array αποκωδικοποιείται σε A15=0, A14=1. Το `out (c),c` με B=#7F
; δίνει θύρα #7Fxx, όπου xx η ίδια η τιμή που γράφεται.
GA_PORT_HI      equ  #7F
ORG_BASE        equ  #C0        ; καμία τράπεζα: η κανονική διάταξη
ORG_BANK0       equ  #C4        ; πρώτη τράπεζα· #C4..#C7 = μπλοκ 4..7
BANK_COUNT      equ  4
BANK_WIN        equ  #4000      ; αρχή του παραθύρου
BANK_WIN_SZ     equ  #4000      ; και το μέγεθός του

;---------------------------------------------------------------------
; bank_probe — υπάρχουν όντως δεύτερα 64 KB, και επιτρέπεται να τα δούμε;
;
;   Δύο ανεξάρτητοι έλεγχοι, και οι δύο πρέπει να περάσουν:
;
;   1. Η ΣΤΟΙΒΑ ΕΞΩ ΑΠΟ ΤΟ ΠΑΡΑΘΥΡΟ. Ο loader κάνει MEMORY &3FFF, οπότε η
;      στοίβα της BASIC κάθεται κάτω από το #4000 και είναι εντάξει. Αυτό
;      όμως είναι ΣΥΜΠΕΡΑΣΜΑ, όχι εγγύηση: αν κάποτε δεν ισχύει, το ίδιο το
;      CALL προς το bank_copy θα πέθαινε τη στιγμή που ανοίγει το παράθυρο,
;      χωρίς κανένα σημάδι. Δέκα bytes ελέγχου, και η αποτυχία σημαίνει
;      απλώς «δισκέτα, όπως πάντα».
;
;   2. ΚΡΑΤΑΕΙ Η ΤΡΑΠΕΖΑ. Σε μηχάνημα 64 KB (464, 664, ή 6128 σε προφίλ 64K
;      στον emulator) το OUT αγνοείται σιωπηλά: γράφεις στην τράπεζα και
;      γράφεις στη βασική μνήμη. Χωρίς αυτόν τον έλεγχο οι αίθουσες θα
;      διαβάζονταν πάνω από τον ίδιο τον κώδικα του παιχνιδιού.
;
;   Ο έλεγχος γράφει σε ΠΡΑΓΜΑΤΙΚΟ byte του προγράμματος (#4000, η πρώτη
;   εντολή) και το επαναφέρει. Δεν υπάρχει «ελεύθερο» byte μέσα στο παράθυρο
;   — όλο είναι κώδικας ή δεδομένα.
;
; OUT: bank_ok = 1 αν οι τράπεζες είναι διαθέσιμες, αλλιώς 0
; ΑΛΛΟΙΩΝΕΙ: AF, BC, HL
;---------------------------------------------------------------------
bank_probe:     xor  a
                ld   (bank_ok),a

                ld   hl,0               ; HL = SP, χωρίς να πειραχτεί η στοίβα
                add  hl,sp
                ld   a,h
                and  #C0
                cp   BANK_WIN >> 8      ; μέσα στο #4000..#7FFF;
                ret  z                  ; τότε καμία εναλλαγή, ποτέ

                ; Το BC κρατά ΠΑΝΤΑ τη θύρα (#7F00 | οργάνωση) και το
                ; `out (c),c` γράφει το χαμηλό byte της ίδιας της θύρας —
                ; ακριβώς όπως το κάνει και η ROM του 6128. Το φυλαγμένο byte
                ; του προγράμματος ζει στο D, μακριά από το BC.
                di                      ; το παράθυρο δεν μένει ανοιχτό όσο
                ld   hl,BANK_WIN        ; τρέχει οτιδήποτε άλλο
                ld   d,(hl)             ; το αληθινό byte του προγράμματος

                ld   bc,GA_PORT_HI*256+ORG_BANK0
                out  (c),c              ; τράπεζα μέσα
                ld   (hl),#A5

                ld   bc,GA_PORT_HI*256+ORG_BASE
                out  (c),c              ; βασική μνήμη
                ld   (hl),#5A           ; ίδια διεύθυνση, άλλη τιμή

                ld   bc,GA_PORT_HI*256+ORG_BANK0
                out  (c),c
                ld   e,(hl)             ; κράτησε η τράπεζα τη δική της;

                ld   bc,GA_PORT_HI*256+ORG_BASE
                out  (c),c              ; πίσω στα κανονικά, ΠΑΝΤΑ
                ld   (hl),d             ; και ο κώδικας όπως τον βρήκαμε
                ei

                ld   a,e
                cp   #A5
                ret  nz                 ; τα δύο γραψίματα πήγαν στο ίδιο
                ld   a,1                ; μέρος: μηχάνημα 64K
                ld   (bank_ok),a
                ret

;---------------------------------------------------------------------
; bank_copy — αντιγράφει από τράπεζα σε βασική μνήμη
;
;   ΜΟΝΟ το LDIR τρέχει με ανοιχτό παράθυρο. Καμία κλήση, κανένα άλμα σε
;   κώδικα του #4000..#7FFF, καμία πρόσβαση σε δεδομένα του — ΚΑΙ ΚΑΜΙΑ ΣΤΟΙΒΑ.
;   Εδώ υπήρχε ένα `pop bc` μετά το άνοιγμα, που είναι ακριβώς πρόσβαση σε
;   δεδομένα του παραθύρου αν η στοίβα τυχαίνει να ζει εκεί. Στο παιχνίδι δεν
;   ζει (loader: MEMORY &3FFF) και ο έλεγχος του bank_probe το επιβάλλει, οπότε
;   ήταν ακίνδυνο· στο src/musictest.asm, όπου ο loader ΠΡΕΠΕΙ να κάνει
;   MEMORY &7FFF, το ίδιο μοτίβο έδωσε BC=#FFFF και ένα LDIR 64 KB πάνω στο
;   πρόγραμμα. Το πλήθος φυλάγεται σε μεταβλητή· δύο bytes, μηδέν εξάρτηση.
;
;   DI ΓΥΡΩ ΑΠΟ ΤΟ ΑΝΟΙΓΜΑ: δεν το απαιτεί το SOFT968 (η διαδρομή διακοπών
;   ζει ολόκληρη έξω από το παράθυρο — RST 7 στο #0038 κάνει jp #B941, οι
;   μεταβλητές firmware ξεκινούν στο #B100), αλλά το παιχνίδι δίνει στο
;   firmware δύο δείκτες που ΕΙΝΑΙ μέσα στο παράθυρο: τα snd_block και
;   sfx_block. Το SOUND QUEUE αντιγράφει το μπλοκ όταν το καλείς, οπότε
;   θεωρητικά δεν το ξαναδιαβάζει — αλλά «θεωρητικά» δεν είναι λόγος να
;   αφήσεις μια ολόκληρη κατηγορία σφάλματος ανοιχτή για 21.000 κύκλους.
;   Το κόστος είναι 0,27 του καρέ για 1 KB· ο ticker των 300 Hz δεν το νιώθει.
;
; IN:  A  = οργάνωση (#C4..#C7)
;      HL = πηγή, ΜΕΣΑ στο #4000..#7FFF
;      DE = προορισμός, ΕΞΩ από το #4000..#7FFF
;      BC = πλήθος bytes
; ΑΛΛΟΙΩΝΕΙ: τα πάντα
;---------------------------------------------------------------------
bank_copy:      di                      ; ΠΡΙΝ το άνοιγμα, όχι μετά: αλλιώς
                ld   (bk_len),bc        ; μένει ένα παράθυρο δύο εντολών όπου
                ld   b,GA_PORT_HI       ; μια διακοπή βλέπει την τράπεζα
                ld   c,a
                out  (c),c              ; σελίδα ΜΕΣΑ
                ld   bc,(bk_len)        ; ΕΞΩ από το παράθυρο, όχι στη στοίβα
                ldir                    ; ΤΟ ΜΟΝΟ που τρέχει ανοιχτό
                ld   bc,GA_PORT_HI*256+ORG_BASE
                out  (c),c              ; σελίδα ΕΞΩ
                ei
                ret

;---------------------------------------------------------------------
; bank_fill — αντιγράφει από βασική μνήμη ΠΡΟΣ τράπεζα
;   Το αντίστροφο του bank_copy, για το γέμισμα κατά την εκκίνηση.
; IN:  A  = οργάνωση, HL = πηγή ΕΞΩ, DE = προορισμός ΜΕΣΑ, BC = πλήθος
; ΑΛΛΟΙΩΝΕΙ: τα πάντα
;---------------------------------------------------------------------
bank_fill:      di
                ld   (bk_len),bc
                ld   b,GA_PORT_HI
                ld   c,a
                out  (c),c
                ld   bc,(bk_len)
                ldir
                ld   bc,GA_PORT_HI*256+ORG_BASE
                out  (c),c
                ei
                ret

; Το πλήθος του LDIR, εδώ κι όχι στη στοίβα: το bank_copy/bank_fill πρέπει να
; το ξαναδιαβάσει ΑΦΟΥ έχει σελιδοποιήσει, και η στοίβα μπορεί να είναι μέσα.
bk_len          dw   0

;---------------------------------------------------------------------
; slot_addr — πού κάθεται το σετ A μέσα στην τράπεζά του
;
;   Ο ΙΔΙΟΣ υπολογισμός με το slot_of του tools/roomfile.py, και ο λόγος που
;   οι θέσεις είναι σταθερού μεγέθους: δύο ολισθήσεις αντί για αναζήτηση σε
;   πίνακα offsets που θα μπορούσε να ξεσυγχρονιστεί με τη δισκέτα.
;
; IN:  A = δείκτης σετ (1..MAX_SETS)
; OUT: HL = διεύθυνση μέσα στο παράθυρο, C = οργάνωση (#C4..#C7)
; ΑΛΛΟΙΩΝΕΙ: AF, BC, HL
;---------------------------------------------------------------------
slot_addr:      dec  a                  ; 1-based -> 0-based
                ld   b,a
                and  (1<<SLOTS_SHIFT)-1 ; ποια θέση μέσα στο μπλοκ
                ; Η θέση είναι πολλαπλάσιο των 256, οπότε ο πολλαπλασιασμός
                ; γίνεται ΜΟΝΟ στο ψηλό byte και το χαμηλό είναι πάντα 0.
                ; Το repeat κρατά τον κώδικα σωστό όποιο κι αν γίνει το
                ; SLOT_SHIFT — με καρφωμένα δύο add a,a, μια αλλαγή του
                ; μεγέθους θέσης θα διάβαζε σιωπηλά από λάθος διεύθυνση.
                repeat SLOT_SHIFT-8
                add  a,a
                rend
                add  a,BANK_WIN >> 8
                ld   h,a
                ld   l,0
                ld   a,b
                ; idx >> SLOTS_SHIFT = ποιο μπλοκ. ΞΑΝΑ με repeat: με καρφωμένες
                ; τέσσερις rrca, η αλλαγή του μεγέθους θέσης από 1 KB σε 512
                ; έστελνε τα μισά σετ σε λάθος τράπεζα — και το τεστ το έπιασε.
                ; Τα bits που ξεχειλίζουν από τη rrca τα κόβει το and.
                repeat SLOTS_SHIFT
                rrca
                rend
                and  BANK_COUNT-1
                add  a,ORG_BANK0
                ld   c,a
                ret

;---------------------------------------------------------------------
; slot_bit — η θέση του σετ A μέσα στον χάρτη γεμάτων θέσεων
; IN:  A = δείκτης σετ
; OUT: HL -> το byte του χάρτη, A = η μάσκα του bit
; ΑΛΛΟΙΩΝΕΙ: AF, BC, DE, HL
;---------------------------------------------------------------------
slot_bit:       dec  a
                ld   c,a
                and  7                  ; ποιο bit μέσα στο byte
                inc  a
                ld   b,a
                ld   a,1
sb_sh:          dec  b
                jr   z,sb_got
                add  a,a
                jr   sb_sh
sb_got:         ld   b,a
                ld   a,c
                rrca                    ; idx >> 3 = ποιο byte
                rrca
                rrca
                and  (MAX_SETS/8)-1
                ld   l,a
                ld   h,0
                ld   de,bank_map
                add  hl,de
                ld   a,b
                ret

;---------------------------------------------------------------------
; slot_full — γέμισε η θέση του σετ A στην εκκίνηση;
; IN:  A = δείκτης σετ      OUT: CF=1 γεμάτη
; ΑΛΛΟΙΩΝΕΙ: AF, BC, DE, HL
;---------------------------------------------------------------------
slot_full:      cp   MAX_SETS+1
                jr   nc,sf_no           ; έξω από τον χάρτη: δεν υπάρχει
                call slot_bit
                and  (hl)
                ret  z                  ; το and αφήνει CF=0
                scf
                ret
sf_no:          or   a
                ret

;---------------------------------------------------------------------
; slot_copy — φέρνει το σετ A από την τράπεζά του στον set_buf
; IN:  A = δείκτης σετ
; ΑΛΛΟΙΩΝΕΙ: τα πάντα
;---------------------------------------------------------------------
;   ΟΣΑ ΧΩΡΑΕΙ Ο BUFFER, όχι ολόκληρη τη θέση. Ο buffer μικραίνει σε κάθε
;   γραμμή κώδικα που προστίθεται, ενώ η θέση είναι σταθερή — αντιγράφοντας
;   set_capacity προσαρμόζεται μόνο του. Το tools/roomfile.py εγγυάται και τα
;   δύο άκρα: κάθε σετ χωράει στον buffer, και ο buffer δεν ξεπερνά τη θέση
;   (αλλιώς θα διαβάζαμε μέσα στην επόμενη — ή έξω από την τράπεζα).
slot_copy:      call slot_addr          ; HL = πηγή, C = οργάνωση
                ld   a,c
                ld   de,set_buf
                ld   bc,set_capacity
                jp   bank_copy

;---------------------------------------------------------------------
; bank_boot — γεμίζει τις θέσεις από τη δισκέτα, ΜΙΑ φορά ανά εκτέλεση
;
;   Χρησιμοποιεί τον ΔΟΚΙΜΑΣΜΕΝΟ δρόμο (set_disc) και δεν εισάγει νέα μορφή
;   αρχείου: οι τράπεζες είναι κρυφή μνήμη πάνω από τη δισκέτα, όχι δεύτερη
;   πηγή αλήθειας. Ένα σετ που λείπει είναι κενό στον χάρτη, όχι σφάλμα — η
;   αρίθμηση των αιθουσών μπορεί να έχει τρύπες.
;
;   ΤΟ ΤΙΜΗΜΑ: μία διαβασιά ανά σετ στην εκκίνηση. Το κερδίζει πίσω στην
;   πρώτη κιόλας πόρτα που δεν χτυπά τον δίσκο.
;
; ΑΛΛΟΙΩΝΕΙ: τα πάντα
;---------------------------------------------------------------------
bank_boot:      ld   a,(bank_done)
                or   a
                ret  nz                 ; το ml_again ξαναμπαίνει στο main
                ld   a,1
                ld   (bank_done),a

                call bank_probe
                ld   a,(bank_ok)
                or   a
                ret  z                  ; 64K: μένει η δισκέτα, όπως πάντα

                ld   hl,bank_map        ; καθαρός χάρτης
                ld   de,bank_map+1
                ld   bc,MAX_SETS/8-1
                ld   (hl),0
                ldir

                ld   a,1
bb_lp:          ld   (bb_idx),a
                call set_disc
                jr   nc,bb_next         ; λείπει: κενό στον χάρτη

                ld   a,(bb_idx)
                call slot_addr          ; HL = προορισμός, C = οργάνωση
                ex   de,hl              ; το bank_fill θέλει DE = προορισμός
                ld   a,c
                ld   hl,set_buf
                ld   bc,set_capacity
                call bank_fill

                ld   a,(bb_idx)
                call slot_bit
                or   (hl)
                ld   (hl),a

                ld   a,(bb_idx)         ; η μπάρα προχωράει και στα σετ που
bb_next:        call boot_bar           ; λείπουν: μετράει ΠΡΟΟΔΟ, όχι επιτυχία
                ld   a,(bb_idx)
                inc  a
                cp   SET_COUNT+1
                jr   c,bb_lp

                xor  a
                ld   (set_cur),a        ; ο set_buf κρατά το τελευταίο σετ,
                ret                     ; αλλά κανείς δεν το έχει ζητήσει

;---------------------------------------------------------------------
; boot_bar — η μπάρα φόρτωσης, ΠΑΝΩ στην οθόνη υποδοχής
;
;   Η οθόνη είναι ακόμα η MODE 0 του loader και μένει εκεί: το SCR_SET_MODE
;   έχει μετακομίσει μετά το γέμισμα, ώστε ο παίκτης να μην κοιτάζει μαύρο.
;   Γράφουμε κατευθείαν στη μνήμη οθόνης — καμία κλήση firmware, καμία
;   αλλαγή παλέτας, τίποτα που να χαλάει την εικόνα από κάτω.
;
;   ΠΡΟΣΟΧΗ: το AMSDOS δανείζεται τα πρώτα 2 KB της οθόνης για buffer, οπότε
;   η εικόνα υποδοχής ΘΑ ριγώσει όσο διαβάζουμε. Δεν υπάρχουν άλλα 2 KB — η
;   μπάρα είναι εκεί ακριβώς για να δείχνει ότι αυτό είναι δουλειά, όχι βλάβη.
;
; IN:  A = πόσα σετ έχουν περάσει
; ΑΛΛΟΙΩΝΕΙ: τα πάντα
;---------------------------------------------------------------------
BAR_X           equ  8          ; στήλη byte
BAR_Y           equ  184        ; πρώτη scanline
BAR_H           equ  8
BAR_W           equ  64         ; πλήρες πλάτος σε bytes
BAR_PEN         equ  #FF        ; MODE 0: όλα τα bits αναμμένα

boot_bar:       or   a
                ret  z
                ld   b,a
                xor  a
bb_mul:         add  a,BAR_STEP
                djnz bb_mul
                cp   BAR_W+1            ; περισσότερα σετ από όσα χωράει η
                jr   c,bb_wok           ; μπάρα: κόβεται στο πλήρες πλάτος
                ld   a,BAR_W
bb_wok:         ld   (bb_w),a
                ld   b,BAR_Y
                ld   c,BAR_H
bb_row:         push bc
                ld   c,BAR_X
                call scr_addr
                ld   a,(bb_w)
                ld   b,a
bb_px:          ld   (hl),BAR_PEN
                inc  hl
                djnz bb_px
                pop  bc
                inc  b
                dec  c
                jr   nz,bb_row
                ret

bb_w            db   0
bb_idx          db   0
bank_done       db   0          ; το γέμισμα γίνεται μία φορά, όχι ανά παρτίδα
bank_map        ds   MAX_SETS/8 ; ένα bit ανά θέση: γέμισε ή όχι
bank_ok         db   0          ; 1 = υπάρχουν τράπεζες και επιτρέπονται

; Ο κώδικας αυτού του αρχείου ΔΕΝ επιτρέπεται να πέσει μέσα στο παράθυρο που
; ο ίδιος εναλλάσσει, ούτε στην οθόνη. Η θέση του include στο main.asm το
; πετυχαίνει σήμερα, αλλά μόνο επειδή τα δεδομένα από πάνω του έχουν αυτό το
; μέγεθος — μια αίθουσα παραπάνω και θα μετακινηθεί.
                assert bank_probe >= #8000
                assert $ < #C000
