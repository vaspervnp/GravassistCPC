;=====================================================================
;  GRAVASSIST — οι τράπεζες RAM του 6128 ως δίσκος αιθουσών
;
;  Ο 6128 έχει δεύτερα 64 KB που το παιχνίδι δεν άγγιζε καθόλου. Μπαίνουν
;  στη μνήμη με τις οργανώσεις #C4..#C7, οι οποίες αντικαθιστούν ΜΟΝΟ το
;  #4000..#7FFF με τα μπλοκ 4..7 — δηλαδή ακριβώς εκεί όπου ζει ΟΛΟΣ ο
;  εκτελέσιμος κώδικας του παιχνιδιού (#4000..#6A05).
;
;  ΑΠΟ ΑΥΤΟ ΠΡΟΚΥΠΤΕΙ Ο ΜΟΝΟΣ ΚΑΝΟΝΑΣ ΤΟΥ ΑΡΧΕΙΟΥ: ό,τι εκτελείται με
;  ανοιχτό παράθυρο ζει ΕΔΩ, και το αρχείο assembl-άρεται πάνω από το #8000.
;  Με ανοιχτό παράθυρο δεν καλείται τίποτα — ούτε firmware, ούτε ρουτίνα του
;  παιχνιδιού, ούτε καν άλλη ρουτίνα αυτού του αρχείου. Μόνο LDIR.
;  Οι δύο assert στο τέλος το επιβάλλουν· η θέση του include είναι σωστή
;  σήμερα κατά τύχη των μεγεθών των δεδομένων, όχι από σχεδιασμό.
;
;  ΓΙΑΤΙ ΩΜΟ OUT ΚΑΙ ΟΧΙ ΤΟ KL BANK SWITCH (#BD5B): το firmware τελειώνει τη
;  ρουτίνα του με ανεπιφύλακτο EI — δεν μπορείς να το καλέσεις μέσα σε δικό
;  σου κρίσιμο τμήμα — και διαβάζει τη θύρα από τον B' του εναλλακτικού
;  σετ, που ανήκει στο firmware. Το ωμό OUT δεν χρωστά τίποτα σε κανέναν.
;
;  Πηγή για τον μηχανισμό: SOFT968 §2.5 και §15, και η ίδια η ROM του 6128
;  (`ld bc,$7fc0 / out (c),c`).
;=====================================================================

; Ο gate array αποκωδικοποιείται σε A15=0, A14=1. Το `out (c),c` με B=#7F
; δίνει θύρα #7Fxx, όπου xx η ίδια η τιμή που γράφεται.
GA_PORT_HI      equ  #7F
ORG_BASE        equ  #C0        ; καμία τράπεζα: η κανονική διάταξη
ORG_BANK0       equ  #C4        ; πρώτη τράπεζα· #C4..#C7 = μπλοκ 4..7
BANK_COUNT      equ  4
BANK_WIN        equ  #4000      ; αρχή του παραθύρου
BANK_WIN_SZ     equ  #4000      ; και το μέγεθός του

;---------------------------------------------------------------------
; bank_probe — υπάρχουν όντως δεύτερα 64 KB, και επιτρέπεται να τα δούμε;
;
;   Δύο ανεξάρτητοι έλεγχοι, και οι δύο πρέπει να περάσουν:
;
;   1. Η ΣΤΟΙΒΑ ΕΞΩ ΑΠΟ ΤΟ ΠΑΡΑΘΥΡΟ. Ο loader κάνει MEMORY &3FFF, οπότε η
;      στοίβα της BASIC κάθεται κάτω από το #4000 και είναι εντάξει. Αυτό
;      όμως είναι ΣΥΜΠΕΡΑΣΜΑ, όχι εγγύηση: αν κάποτε δεν ισχύει, το ίδιο το
;      CALL προς το bank_copy θα πέθαινε τη στιγμή που ανοίγει το παράθυρο,
;      χωρίς κανένα σημάδι. Δέκα bytes ελέγχου, και η αποτυχία σημαίνει
;      απλώς «δισκέτα, όπως πάντα».
;
;   2. ΚΡΑΤΑΕΙ Η ΤΡΑΠΕΖΑ. Σε μηχάνημα 64 KB (464, 664, ή 6128 σε προφίλ 64K
;      στον emulator) το OUT αγνοείται σιωπηλά: γράφεις στην τράπεζα και
;      γράφεις στη βασική μνήμη. Χωρίς αυτόν τον έλεγχο οι αίθουσες θα
;      διαβάζονταν πάνω από τον ίδιο τον κώδικα του παιχνιδιού.
;
;   Ο έλεγχος γράφει σε ΠΡΑΓΜΑΤΙΚΟ byte του προγράμματος (#4000, η πρώτη
;   εντολή) και το επαναφέρει. Δεν υπάρχει «ελεύθερο» byte μέσα στο παράθυρο
;   — όλο είναι κώδικας ή δεδομένα.
;
; OUT: bank_ok = 1 αν οι τράπεζες είναι διαθέσιμες, αλλιώς 0
; ΑΛΛΟΙΩΝΕΙ: AF, BC, HL
;---------------------------------------------------------------------
bank_probe:     xor  a
                ld   (bank_ok),a

                ld   hl,0               ; HL = SP, χωρίς να πειραχτεί η στοίβα
                add  hl,sp
                ld   a,h
                and  #C0
                cp   BANK_WIN >> 8      ; μέσα στο #4000..#7FFF;
                ret  z                  ; τότε καμία εναλλαγή, ποτέ

                ; Το BC κρατά ΠΑΝΤΑ τη θύρα (#7F00 | οργάνωση) και το
                ; `out (c),c` γράφει το χαμηλό byte της ίδιας της θύρας —
                ; ακριβώς όπως το κάνει και η ROM του 6128. Το φυλαγμένο byte
                ; του προγράμματος ζει στο D, μακριά από το BC.
                di                      ; το παράθυρο δεν μένει ανοιχτό όσο
                ld   hl,BANK_WIN        ; τρέχει οτιδήποτε άλλο
                ld   d,(hl)             ; το αληθινό byte του προγράμματος

                ld   bc,GA_PORT_HI*256+ORG_BANK0
                out  (c),c              ; τράπεζα μέσα
                ld   (hl),#A5

                ld   bc,GA_PORT_HI*256+ORG_BASE
                out  (c),c              ; βασική μνήμη
                ld   (hl),#5A           ; ίδια διεύθυνση, άλλη τιμή

                ld   bc,GA_PORT_HI*256+ORG_BANK0
                out  (c),c
                ld   e,(hl)             ; κράτησε η τράπεζα τη δική της;

                ld   bc,GA_PORT_HI*256+ORG_BASE
                out  (c),c              ; πίσω στα κανονικά, ΠΑΝΤΑ
                ld   (hl),d             ; και ο κώδικας όπως τον βρήκαμε
                ei

                ld   a,e
                cp   #A5
                ret  nz                 ; τα δύο γραψίματα πήγαν στο ίδιο
                ld   a,1                ; μέρος: μηχάνημα 64K
                ld   (bank_ok),a
                ret

;---------------------------------------------------------------------
; bank_copy — αντιγράφει από τράπεζα σε βασική μνήμη
;
;   ΜΟΝΟ το LDIR τρέχει με ανοιχτό παράθυρο. Καμία κλήση, κανένα άλμα σε
;   κώδικα του #4000..#7FFF, καμία πρόσβαση σε δεδομένα του.
;
;   DI ΓΥΡΩ ΑΠΟ ΤΟ ΑΝΟΙΓΜΑ: δεν το απαιτεί το SOFT968 (η διαδρομή διακοπών
;   ζει ολόκληρη έξω από το παράθυρο — RST 7 στο #0038 κάνει jp #B941, οι
;   μεταβλητές firmware ξεκινούν στο #B100), αλλά το παιχνίδι δίνει στο
;   firmware δύο δείκτες που ΕΙΝΑΙ μέσα στο παράθυρο: τα snd_block και
;   sfx_block. Το SOUND QUEUE αντιγράφει το μπλοκ όταν το καλείς, οπότε
;   θεωρητικά δεν το ξαναδιαβάζει — αλλά «θεωρητικά» δεν είναι λόγος να
;   αφήσεις μια ολόκληρη κατηγορία σφάλματος ανοιχτή για 21.000 κύκλους.
;   Το κόστος είναι 0,27 του καρέ για 1 KB· ο ticker των 300 Hz δεν το νιώθει.
;
; IN:  A  = οργάνωση (#C4..#C7)
;      HL = πηγή, ΜΕΣΑ στο #4000..#7FFF
;      DE = προορισμός, ΕΞΩ από το #4000..#7FFF
;      BC = πλήθος bytes
; ΑΛΛΟΙΩΝΕΙ: τα πάντα
;---------------------------------------------------------------------
bank_copy:      di                      ; ΠΡΙΝ το άνοιγμα, όχι μετά: αλλιώς
                push bc                 ; μένει ένα παράθυρο δύο εντολών όπου
                ld   b,GA_PORT_HI       ; μια διακοπή βλέπει την τράπεζα
                ld   c,a
                out  (c),c              ; σελίδα ΜΕΣΑ
                pop  bc
                ldir                    ; ΤΟ ΜΟΝΟ που τρέχει ανοιχτό
                ld   bc,GA_PORT_HI*256+ORG_BASE
                out  (c),c              ; σελίδα ΕΞΩ
                ei
                ret

;---------------------------------------------------------------------
; bank_fill — αντιγράφει από βασική μνήμη ΠΡΟΣ τράπεζα
;   Το αντίστροφο του bank_copy, για το γέμισμα κατά την εκκίνηση.
; IN:  A  = οργάνωση, HL = πηγή ΕΞΩ, DE = προορισμός ΜΕΣΑ, BC = πλήθος
; ΑΛΛΟΙΩΝΕΙ: τα πάντα
;---------------------------------------------------------------------
bank_fill:      di
                push bc
                ld   b,GA_PORT_HI
                ld   c,a
                out  (c),c
                pop  bc
                ldir
                ld   bc,GA_PORT_HI*256+ORG_BASE
                out  (c),c
                ei
                ret

bank_ok         db   0          ; 1 = υπάρχουν τράπεζες και επιτρέπονται

; Ο κώδικας αυτού του αρχείου ΔΕΝ επιτρέπεται να πέσει μέσα στο παράθυρο που
; ο ίδιος εναλλάσσει, ούτε στην οθόνη. Η θέση του include στο main.asm το
; πετυχαίνει σήμερα, αλλά μόνο επειδή τα δεδομένα από πάνω του έχουν αυτό το
; μέγεθος — μια αίθουσα παραπάνω και θα μετακινηθεί.
                assert bank_probe >= #8000
                assert $ < #C000
