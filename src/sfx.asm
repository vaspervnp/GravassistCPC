; ---------------------------------------------------------------------------
; sfx.asm — ηχητικά εφέ του παιχνιδιού
;
; ΤΙ ΚΑΝΕΙ: μια κλήση `sfx_play` με έναν αριθμό εφέ σπρώχνει 1-4 μπλοκ στην
; ουρά ήχου του firmware. Το firmware τα παίζει με τον δικό του ρυθμό (300 Hz
; ticker), οπότε το παιχνίδι δεν χρειάζεται ούτε χρονισμό ούτε interrupt.
;
; ΤΑ ΚΑΝΑΛΙΑ ΕΙΝΑΙ ΜΟΙΡΑΣΜΕΝΑ ΚΑΤΑ ΡΟΛΟ, όχι κατά εφέ:
;   A = ενέργειες (διακόπτης, πύλη, κλειδαριά, τηλεμεταφορά, πόρτες, χτύπημα)
;   B = βήματα και κιβώτια — ό,τι επαναλαμβάνεται συχνά
;   C = παράσιτα στη ζώνη κλειδώματος βαρύτητας
; Ο λόγος είναι η ουρά: είναι FIFO ΑΝΑ ΚΑΝΑΛΙ. Αν τα βήματα έμπαιναν στο ίδιο
; κανάλι με τις ενέργειες, ένας διακόπτης που πατάς ενώ περπατάς θα ακουγόταν
; μισό δευτερόλεπτο αργότερα — πίσω από τα βήματα.
;
; ΓΕΜΑΤΗ ΟΥΡΑ = ΠΕΤΑΜΕ ΤΟ ΕΦΕ, δεν το ξαναδοκιμάζουμε. Αντίθετα με τη μουσική
; (musicplay.asm), που ΠΡΕΠΕΙ να ξαναδοκιμάσει αλλιώς χάνει νότα: ένα εφέ που
; θα ακουστεί αργότερα είναι χειρότερο από εφέ που δεν ακούστηκε, γιατί
; αναφέρεται σε κάτι που ήδη πέρασε.
;
; Στο παιχνίδι δεν παίζει μουσική (το menu_show κλείνει με music_stop ->
; SOUND_RESET), οπότε και τα τρία κανάλια είναι δικά μας και οι ουρές άδειες.
; ---------------------------------------------------------------------------

SFX_QUEUE       equ  #BCAA      ; HL = μπλοκ· CF=1 μπήκε, CF=0 γεμάτη ουρά
                                ; ΧΑΛΑΕΙ: AF,BC,DE,HL

; --- κανάλια (bit 0-2 του byte κατάστασης)
SFXCH_ACT       equ  1          ; A
SFXCH_MOVE      equ  2          ; B
SFXCH_AMB       equ  4          ; C

; --- αριθμοί εφέ, όπως τα καλεί το υπόλοιπο παιχνίδι
SFXID_STEP      equ  0          ; πάτημα ποδιού
SFXID_SWITCH    equ  1          ; γύρισμα διακόπτη
SFXID_GATE      equ  2          ; άνοιγμα πύλης
SFXID_PLATE     equ  3          ; πάτημα πλάκας πίεσης
SFXID_UNLOCK    equ  4          ; ξεκλείδωμα
SFXID_TELE      equ  5          ; τηλεμεταφορά
SFXID_DROP      equ  6          ; άφημα κιβωτίου
SFXID_THUD      equ  7          ; κιβώτιο που προσγειώνεται
SFXID_EXIT      equ  8          ; έξοδος από δωμάτιο
SFXID_ENTER     equ  9          ; είσοδος σε δωμάτιο
SFXID_HURT      equ  10         ; χτύπημα (αγκάθια ή πτώση)
SFXID_OVER      equ  11         ; τέλος παιχνιδιού
SFX_COUNT       equ  12

; Κάθε βήμα είναι 5 bytes: περίοδος τόνου (2), θόρυβος, ένταση, διάρκεια σε
; εκατοστά του δευτερολέπτου. Η περίοδος βγαίνει 125000/συχνότητα.
SFX_STEPSZ      equ  5

;---------------------------------------------------------------------
; sfx_chan — σε ποιο κανάλι θα ακουστεί στ' αλήθεια το εφέ
;
;   Με τη μουσική αναμμένη ΜΕΣΑ σε δωμάτιο, τα εφέ μαζεύονται όλα στο B. Το A
;   και το C παίζουν μπάσο και τύμπανα, και ένα εφέ εκεί θα είχε δύο επιλογές,
;   και οι δύο κακές: ή να μπει στην ουρά πίσω από τη μουσική και να ακουστεί
;   αργότερα, ή να σηκώσει το bit αδειάσματος και να πετάξει νότες που ο
;   player έχει ήδη μετρήσει ως παιγμένες — οπότε εκείνη η φωνή θα έτρεχε
;   μπροστά από τις άλλες δύο, λίγο περισσότερο με κάθε βήμα.
;
;   Το τίμημα είναι ότι δύο εφέ μαζί κόβει το ένα το άλλο. Γι' αυτό ακριβώς
;   υπάρχει η επιλογή M στο μενού.
;
; IN:  A = το κανάλι που ζητά το εφέ (bit 7 = άδειασμα)
; OUT: A = αυτό που θα γραφτεί στο μπλοκ
; ΑΛΛΟΙΩΝΕΙ: F
;---------------------------------------------------------------------
sfx_chan:       push bc
                ld   c,a
                ld   a,(music_on)
                or   a
                jr   z,sc_keep
                ld   a,(tune_ok)
                or   a
                jr   z,sc_keep
                ld   a,(mus_quiet)      ; 0 = μενού/τέλος, εκεί δεν παίζουν εφέ
                or   a
                jr   z,sc_keep
                ; ΚΑΙ ΧΩΡΙΣ ΤΗ ΣΗΜΑΙΑ ΑΔΕΙΑΣΜΑΤΟΣ. Το bit 7 το σηκώνει μόνο το
                ; σβήσιμο των παρασίτων, για να κόψει τον τελευταίο κρότο· όταν
                ; όλα τα εφέ μοιράζονται το B, αυτό θα έσβηνε ό,τι άλλο περίμενε
                ; στην ουρά — ένα βήμα, μια πύλη. Το να τελειώσει μόνος του ο
                ; τελευταίος κρότος κοστίζει δέκατα του δευτερολέπτου· το να
                ; χαθεί ο ήχος μιας ενέργειας φαίνεται σαν χαλασμένο παιχνίδι.
                ld   a,SFXCH_MOVE
                pop  bc
                ret
sc_keep:        ld   a,c
                pop  bc
                ret

; ---------------------------------------------------------------------------
; sfx_play — παίζει ένα εφέ
; IN:  A = SFXID_*
; OUT: —
; ΑΛΛΟΙΩΝΕΙ: AF,BC,DE,HL
;
; Άγνωστος αριθμός αγνοείται σιωπηλά: ένα εφέ δεν αξίζει να ρίξει το παιχνίδι.
; ---------------------------------------------------------------------------
sfx_play:
                cp   SFX_COUNT
                ret  nc


                ; HL = sfx_table[A] (πίνακας 16-bit δεικτών)
                add  a,a
                ld   l,a
                ld   h,0
                ld   de,sfx_table
                add  hl,de
                ld   e,(hl)
                inc  hl
                ld   d,(hl)
                ex   de,hl              ; HL -> ορισμός εφέ

                ld   a,(hl)             ; κανάλι
                inc  hl
                call sfx_chan
                ld   (sfxb_chan),a
                ld   b,(hl)             ; πλήθος βημάτων
                inc  hl

sfx_next:       push bc
                push hl
                call sfx_one
                pop  hl
                pop  bc
                ret  nc                 ; γεμάτη ουρά: κόβουμε το υπόλοιπο εφέ
                ld   de,SFX_STEPSZ
                add  hl,de
                djnz sfx_next
                ret

; --- ένα βήμα: HL -> τα 5 bytes. OUT: CF από το SOUND QUEUE.
sfx_one:
                ld   a,(hl)             ; περίοδος τόνου, low
                ld   (sfxb_tone),a
                inc  hl
                ld   a,(hl)             ; high
                ld   (sfxb_tone+1),a
                inc  hl
                ld   a,(hl)             ; θόρυβος
                ld   (sfxb_noise),a
                inc  hl
                ld   a,(hl)             ; ένταση
                ld   (sfxb_vol),a
                inc  hl
                ld   a,(hl)             ; διάρκεια (1 byte· το high μένει 0)
                ld   (sfxb_dur),a
                ld   hl,sfx_block
                jp   SFX_QUEUE          ; το CF του δίνει την απάντηση

; ---------------------------------------------------------------------------
; ΠΑΡΑΣΙΤΑ ΣΤΗ ΖΩΝΗ ΚΛΕΙΔΩΜΑΤΟΣ ΒΑΡΥΤΗΤΑΣ
;
; Δεν είναι εφέ μιας βολής αλλά ΚΑΤΑΣΤΑΣΗ: όσο ο ήρωας είναι μέσα στη ζώνη
; ακούγεται σιγανός θόρυβος. Το πετυχαίνουμε βάζοντας στην ουρά ένα κομμάτι
; θορύβου κάθε SFX_AMB_EVERY καρέ, λίγο ΜΑΚΡΥΤΕΡΟ από το διάστημα αυτό ώστε
; τα κομμάτια να επικαλύπτονται και ο ήχος να μην κόβεται ανάμεσά τους.
;
; Στην έξοδο από τη ζώνη ΔΕΝ αρκεί να σταματήσουμε να στέλνουμε: θα έμενε ό,τι
; έχει ήδη μπει στην ουρά. Γι' αυτό στέλνουμε ένα μπλοκ με τη σημαία flush
; (bit 7), που αδειάζει το κανάλι ΑΜΕΣΩΣ.
; ---------------------------------------------------------------------------
SFX_AMB_EVERY   equ  8          ; καρέ ανάμεσα σε δύο κομμάτια
SFX_AMB_DUR     equ  24         ; εκατοστά — 8 καρέ = 16, άρα επικαλύπτονται
SFX_AMB_VOL     equ  3          ; σιγανά· ο ήχος είναι υπόκρουση, όχι εφέ
SFX_AMB_NOISE   equ  26         ; χαμηλόσυχνο σφύριγμα

; ---------------------------------------------------------------------------
; sfx_amb — δηλώνει αν ο ήρωας είναι ΤΩΡΑ μέσα σε ζώνη κλειδώματος
; IN:  A = 0 έξω, οτιδήποτε άλλο μέσα
; ΑΛΛΟΙΩΝΕΙ: AF,BC,DE,HL
; Καλείται ΚΑΘΕ ΚΑΡΕ· η ίδια κρατά τον μετρητή.
; ---------------------------------------------------------------------------
sfx_amb:
                or   a
                jr   z,sfx_amb_off

                ld   a,(sfx_amb_on)
                or   a
                jr   nz,sfx_amb_cont
                ld   a,1                ; μόλις μπήκε: ακούγεται αμέσως
                ld   (sfx_amb_on),a
                xor  a
                ld   (sfx_amb_ctr),a

sfx_amb_cont:   ld   a,(sfx_amb_ctr)
                dec  a
                jp   p,sfx_amb_wait     ; θετικό: απλώς μετράμε
                ld   a,SFX_AMB_EVERY-1
                ld   (sfx_amb_ctr),a

                ld   a,SFXCH_AMB
                call sfx_chan
                ld   (sfxb_chan),a
                xor  a                  ; χωρίς τόνο — μόνο θόρυβος
                ld   (sfxb_tone),a
                ld   (sfxb_tone+1),a
                ld   a,SFX_AMB_NOISE
                ld   (sfxb_noise),a
                ld   a,SFX_AMB_VOL
                ld   (sfxb_vol),a
                ld   a,SFX_AMB_DUR
                ld   (sfxb_dur),a
                ld   hl,sfx_block
                jp   SFX_QUEUE          ; γεμάτη ουρά; τότε ήδη ακούγεται

sfx_amb_wait:   ld   (sfx_amb_ctr),a
                ret

; --- έξοδος από τη ζώνη: σιωπή ΤΩΡΑ, όχι όταν αδειάσει η ουρά
sfx_amb_off:    ld   a,(sfx_amb_on)
                or   a
                ret  z
                xor  a
                ld   (sfx_amb_on),a
                ld   a,SFXCH_AMB+#80    ; bit 7 = άδειασμα του καναλιού
                call sfx_chan
                ld   (sfxb_chan),a
                xor  a
                ld   (sfxb_tone),a
                ld   (sfxb_tone+1),a
                ld   (sfxb_noise),a
                ld   (sfxb_vol),a       ; ένταση 0 = σιωπή
                ld   a,1
                ld   (sfxb_dur),a
                ld   hl,sfx_block
                jp   SFX_QUEUE

; ---------------------------------------------------------------------------
; sfx_reset — σιωπή και μηδενισμός κατάστασης (αλλαγή δωματίου, νέο παιχνίδι)
; ΑΛΛΟΙΩΝΕΙ: AF,BC,DE,HL
; ---------------------------------------------------------------------------
sfx_reset:      xor  a
                ld   (sfx_amb_on),a
                ld   (sfx_amb_ctr),a
                ld   (sfx_gatechg),a
                ret

; ---------------------------------------------------------------------------
; sfx_gate — ο ήχος της πύλης, ΜΙΑ φορά ανά ενέργεια
; ΑΛΛΟΙΩΝΕΙ: AF,BC,DE,HL
;
; Το gate_toggle/gate_set περνούν από ΟΛΕΣ τις πύλες του καναλιού. Ένας ήχος
; ανά πύλη θα έδινε ριπή από τέσσερα «άνοιξε» για μία κίνηση, στοιβαγμένα στην
; ίδια ουρά. Αντ' αυτού σηκώνουν σημαία και ο ήχος παίζει εδώ, μία φορά.
; ---------------------------------------------------------------------------
sfx_gate:       ld   hl,sfx_gatechg
                ld   a,(hl)
                or   a
                ret  z
                ld   (hl),0
                ld   a,SFXID_GATE
                jp   sfx_play

; ---------------------------------------------------------------------------
; Τα εφέ. Περίοδος = 125000 / συχνότητα σε Hz.
; ---------------------------------------------------------------------------
sfx_table:      dw   sfx_d_step, sfx_d_switch, sfx_d_gate, sfx_d_plate
                dw   sfx_d_unlock, sfx_d_tele, sfx_d_drop, sfx_d_thud
                dw   sfx_d_exit, sfx_d_enter, sfx_d_hurt, sfx_d_over

; Βήμα: πολύ κοντός, ξερός κρότος. Λίγος θόρυβος για «πάτημα σε μέταλλο».
sfx_d_step:     db   SFXCH_MOVE, 1
                dw   420                ; ~300 Hz
                db   20, 5, 2

; Διακόπτης: δύο κρότοι, χαμηλός-ψηλός — «κλακ».
sfx_d_switch:   db   SFXCH_ACT, 2
                dw   595                ; ~210 Hz
                db   0, 12, 3
                dw   298                ; ~420 Hz
                db   0, 11, 4

; Πύλη: ανοδική σκάλα, ακούγεται σαν κάτι που ανοίγει.
sfx_d_gate:     db   SFXCH_ACT, 3
                dw   478                ; ~262 Hz
                db   0, 10, 5
                dw   379                ; ~330 Hz
                db   0, 11, 5
                dw   319                ; ~392 Hz
                db   0, 12, 7

; Πλάκα πίεσης: υπόκωφο «τουκ», με θόρυβο για βάρος.
sfx_d_plate:    db   SFXCH_ACT, 1
                dw   758                ; ~165 Hz
                db   18, 9, 5

; Ξεκλείδωμα: δύο καθαροί ψηλοί τόνοι — «ντινγκ».
sfx_d_unlock:   db   SFXCH_ACT, 2
                dw   239                ; ~523 Hz
                db   0, 11, 4
                dw   159                ; ~784 Hz
                db   0, 12, 8

; Τηλεμεταφορά: γρήγορη ανοδική σάρωση.
sfx_d_tele:     db   SFXCH_ACT, 4
                dw   568                ; ~220 Hz
                db   0, 9, 2
                dw   379
                db   0, 10, 2
                dw   239
                db   0, 11, 2
                dw   142                ; ~880 Hz
                db   0, 12, 5

; Άφημα κιβωτίου: ελαφρύ, κοντό «ταπ».
sfx_d_drop:     db   SFXCH_MOVE, 1
                dw   893                ; ~140 Hz
                db   14, 8, 4

; Κιβώτιο που πέφτει: βαρύ, με περισσότερο θόρυβο και ουρά.
sfx_d_thud:     db   SFXCH_MOVE, 2
                dw   1250               ; ~100 Hz
                db   24, 13, 5
                dw   1667               ; ~75 Hz
                db   20, 7, 6

; Έξοδος: καθοδικό ζεύγος — «φεύγεις».
sfx_d_exit:     db   SFXCH_ACT, 2
                dw   319                ; ~392 Hz
                db   0, 11, 5
                dw   478                ; ~262 Hz
                db   0, 10, 8

; Είσοδος: το ίδιο ανάποδα — «έφτασες».
sfx_d_enter:    db   SFXCH_ACT, 2
                dw   478
                db   0, 10, 5
                dw   319
                db   0, 12, 8

; Χτύπημα: τραχύ, θόρυβος πάνω από χαμηλό τόνο.
sfx_d_hurt:     db   SFXCH_ACT, 2
                dw   1000               ; ~125 Hz
                db   8, 14, 6
                dw   1500
                db   16, 10, 8

; Τέλος: τέσσερις τόνοι που κατεβαίνουν και σβήνουν. Αργοί επίτηδες — ένα
; γρήγορο εφέ θα ακουγόταν σαν λάθος, όχι σαν κλείσιμο.
sfx_d_over:     db   SFXCH_ACT, 4
                dw   478                ; ~262 Hz
                db   0, 13, 14
                dw   568                ; ~220 Hz
                db   0, 12, 14
                dw   716                ; ~175 Hz
                db   0, 11, 18
                dw   955                ; ~131 Hz
                db   0, 9, 40

; ---------------------------------------------------------------------------
; Το μπλοκ που θέλει το SOUND QUEUE — 9 bytes, ίδια διάταξη με το musicplay.
; ΔΙΚΟ ΜΑΣ, ξεχωριστό από το snd_block της μουσικής: τα δύο δεν παίζουν ποτέ
; μαζί σήμερα, αλλά ένα κοινό buffer θα ήταν νάρκη για όποιον βάλει μουσική
; στο παιχνίδι αργότερα.
; ---------------------------------------------------------------------------
sfx_block:
sfxb_chan:      db   0          ; κανάλι (bit 0-2) + σημαίες (bit 7 = flush)
                db   0          ; envelope έντασης — δεν χρησιμοποιούμε
                db   0          ; envelope τόνου
sfxb_tone:      dw   0          ; περίοδος τόνου
sfxb_noise:     db   0          ; περίοδος θορύβου 0-31
sfxb_vol:       db   0          ; ένταση 0-15
sfxb_dur:       dw   0          ; διάρκεια σε 1/100 s (το high μένει πάντα 0)

sfx_amb_on:     db   0          ; είμαστε μέσα σε ζώνη κλειδώματος;
sfx_amb_ctr:    db   0          ; καρέ μέχρι το επόμενο κομμάτι θορύβου
sfx_gatechg:    db   0          ; άλλαξε πύλη σε αυτή την ενέργεια;
