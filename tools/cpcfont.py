GLYPHS = {}
_toks = _HEX.replace("\n", " ").split()
# A glyph is a code followed by 16 hex digits; a stray space inside the hex
# (kept readable above) is tolerated by gluing tokens until 16 digits.
_i = 0
while _i < len(_toks):
    code = int(_toks[_i])
    _i += 1
    hx = ""
    while len(hx) < 16:
        hx += _toks[_i]
        _i += 1
    GLYPHS[code] = bytes.fromhex(hx)

assert len(GLYPHS) == 96 and all(len(g) == 8 for g in GLYPHS.values())


def glyph(code):
    return GLYPHS.get(code, bytes(8))
